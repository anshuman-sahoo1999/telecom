import { API_BASE_URL } from "../config";
import React, { useState, useEffect, useMemo, useCallback, useRef } from "react";
import axios from "axios";
import { saveAs } from "file-saver";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { FileSpreadsheet, FileText, Download, ChevronDown } from "lucide-react";
import "../style/rawdata.css";

const PAGE_SIZES = [25, 50, 100, 500, "All"];

// OTP, Final OTP, QC Rating, No. of Returns, Final No. of Returns -> shown as whole-number % (0.84 -> 84%)
const PERCENT_KEYS = ["otp", "final_otp", "qc_rating", "no_of_returns", "final_no_of_returns"];
const PERCENT_HEADERS = ["otp", "finalotp", "qcrating", "noofreturns", "finalnoofreturns"];
const fmtPct = (v) => {
  const n = Number(v);
  return Number.isNaN(n) ? String(v) : `${Math.round(n * 100)}%`;
};
const fmtCell = (key, v) => {
  if (v === null || v === undefined || v === "") return "";
  return PERCENT_KEYS.includes(key) ? fmtPct(v) : String(v);
};

export default function RawDataReport() {
  const [domains, setDomains] = useState([]);
  const [domain, setDomain] = useState("ALL");
  const [columns, setColumns] = useState([]);
  const [rows, setRows] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [page, setPage] = useState(1);
  const [pageSize, setPageSize] = useState(50);
  const [exporting, setExporting] = useState("");
  const [exportOpen, setExportOpen] = useState(false);
  const exportRef = useRef(null);

  /* close Export dropdown on outside click / Esc */
  useEffect(() => {
    const onDown = (e) => {
      if (exportRef.current && !exportRef.current.contains(e.target)) setExportOpen(false);
    };
    const onKey = (e) => e.key === "Escape" && setExportOpen(false);
    document.addEventListener("mousedown", onDown);
    document.addEventListener("keydown", onKey);
    return () => {
      document.removeEventListener("mousedown", onDown);
      document.removeEventListener("keydown", onKey);
    };
  }, []);

  /* domain dropdown */
  useEffect(() => {
    axios
      .get(`${API_BASE_URL}/api/rawdata/domains`)
      .then((r) => setDomains(r.data?.data || []))
      .catch(() => {});
  }, []);

  /* table data (reloads on domain change) */
  const load = useCallback(async (d) => {
    setLoading(true);
    setError("");
    try {
      const res = await axios.get(`${API_BASE_URL}/api/rawdata`, { params: { domain: d } });
      setColumns(res.data?.columns || []);
      setRows(res.data?.data || []);
      setPage(1);
    } catch (e) {
      setError(e.response?.data?.message || "Could not load the data.");
      setRows([]);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load(domain);
  }, [domain, load]);

  const totalPages = pageSize === "All" ? 1 : Math.max(1, Math.ceil(rows.length / pageSize));
  const pageRows = useMemo(() => {
    if (pageSize === "All") return rows;
    const s = (page - 1) * pageSize;
    return rows.slice(s, s + pageSize);
  }, [rows, page, pageSize]);

  const label = domain === "ALL" ? "All_Domains" : domain.replace(/[^\w-]+/g, "_");

  /* ---- Export Excel (generated by backend) ---- */
  const exportExcel = async () => {
    setExporting("excel");
    try {
      const res = await axios.get(`${API_BASE_URL}/api/rawdata/export/excel`, {
        params: { domain },
        responseType: "blob",
      });
      saveAs(res.data, `Raw_Data_Report_${label}.xlsx`);
    } catch (e) {
      setError("Excel export failed. Please try again.");
    } finally {
      setExporting("");
    }
  };

  /* ---- Export PDF (full data of the selected domain) ---- */
  const exportPdf = () => {
    setExporting("pdf");
    try {
      const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a3" });
      doc.setFontSize(16);
      doc.setTextColor(30, 58, 138);
      doc.text("Raw Data Report", 30, 32);
      doc.setFontSize(10);
      doc.setTextColor(80);
      doc.text(
        `Domain: ${domain === "ALL" ? "All Domains" : domain}   |   Total Rows: ${rows.length}   |   Generated: ${new Date().toLocaleString()}`,
        30,
        50
      );

      autoTable(doc, {
        startY: 62,
        head: [columns.map((c) => c.header)],
        body: rows.map((r) => columns.map((c) => fmtCell(c.key, r[c.key]))),
        styles: { fontSize: 6, cellPadding: 2, overflow: "linebreak" },
        headStyles: { fillColor: [30, 58, 138], textColor: 255, fontSize: 6, halign: "center" },
        alternateRowStyles: { fillColor: [244, 247, 252] },
        margin: { left: 20, right: 20, bottom: 28 },
        didDrawPage: () => {
          doc.setFontSize(8);
          doc.setTextColor(120);
          doc.text(
            `Page ${doc.getNumberOfPages()}`,
            doc.internal.pageSize.getWidth() - 60,
            doc.internal.pageSize.getHeight() - 12
          );
        },
      });
      doc.save(`Raw_Data_Report_${label}.pdf`);
    } catch (e) {
      console.error(e);
      setError("PDF export failed. Please try again.");
    } finally {
      setExporting("");
    }
  };

  const noData = !loading && rows.length === 0;

  return (
    <div className="rd-page">
      <h2 className="rd-title">Raw Data Report</h2>

      <div className="rd-card rd-card-plain">
        {/* top: left = Domain select, right = Export dropdown (Excel / PDF) */}
        <div className="rd-toolbar">
          <div className="left">
            <label htmlFor="rd-domain">Domain</label>
            <select
              id="rd-domain"
              className="rd-select"
              value={domain}
              onChange={(e) => setDomain(e.target.value)}
            >
              <option value="ALL">All Domains</option>
              {domains.map((d) => (
                <option key={d.domain} value={d.domain}>
                  {d.domain} ({d.total})
                </option>
              ))}
            </select>
          </div>

          <div className="right">
            <div className="rd-export" ref={exportRef}>
              <button
                className="rd-btn rd-export-btn"
                onClick={() => setExportOpen((o) => !o)}
                disabled={noData || loading || !!exporting}
                aria-haspopup="menu"
                aria-expanded={exportOpen}
              >
                <Download size={16} />
                {exporting === "excel" ? "Exporting Excel..." : exporting === "pdf" ? "Exporting PDF..." : "Export"}
                <ChevronDown size={16} className={exportOpen ? "rd-caret open" : "rd-caret"} />
              </button>

              {exportOpen && (
                <div className="rd-export-menu" role="menu">
                  <button
                    role="menuitem"
                    onClick={() => {
                      setExportOpen(false);
                      exportExcel();
                    }}
                  >
                    <FileSpreadsheet size={16} color="#16a34a" /> Excel (.xlsx)
                  </button>
                  <button
                    role="menuitem"
                    onClick={() => {
                      setExportOpen(false);
                      exportPdf();
                    }}
                  >
                    <FileText size={16} color="#dc2626" /> PDF (.pdf)
                  </button>
                </div>
              )}
            </div>
          </div>
        </div>

        {error && <div style={{ color: "#dc2626", marginBottom: 10, fontWeight: 600 }}>{error}</div>}

        {loading ? (
          <div className="rd-state">Loading...</div>
        ) : noData ? (
          <div className="rd-state">No data found. Please import an Excel file in Raw Data Upload first.</div>
        ) : (
          <>
            <div className="rd-count">Total records: {rows.length}</div>
            <div className="rd-tablewrap">
              <table className="rd-table">
                <thead>
                  <tr>
                    {columns.map((c) => (
                      <th key={c.key}>{c.header}</th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {pageRows.map((r, i) => (
                    <tr key={i}>
                      {columns.map((c) => (
                        <td key={c.key}>{fmtCell(c.key, r[c.key])}</td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            <div className="rd-pager">
              <div className="c">
                Rows per page
                <select
                  value={pageSize}
                  onChange={(e) => {
                    const v = e.target.value;
                    setPageSize(v === "All" ? "All" : Number(v));
                    setPage(1);
                  }}
                >
                  {PAGE_SIZES.map((s) => (
                    <option key={s} value={s}>
                      {s}
                    </option>
                  ))}
                </select>
              </div>
              <div className="c">
                <button className="rd-btn gray sm" disabled={page <= 1} onClick={() => setPage((p) => p - 1)}>
                  Prev
                </button>
                <span>
                  Page {page} / {totalPages}
                </span>
                <button
                  className="rd-btn gray sm"
                  disabled={page >= totalPages}
                  onClick={() => setPage((p) => p + 1)}
                >
                  Next
                </button>
              </div>
            </div>
          </>
        )}
      </div>
    </div>
  );
}
